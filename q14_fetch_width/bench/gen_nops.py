#!/usr/bin/env python3
"""Generate Q14 fetch-width kernels: long unrolled blocks of L-byte NOPs.

    void nop_L_K(uint64_t iters)   # K NOPs of L bytes each, looped `iters` times

Short NOPs hit the instruction-count limit (decode/rename width); long NOPs hit
the byte limit (fetch bandwidth). K sets the code footprint:
small K fits the uop cache, large K forces the legacy decoders and,
eventually, spills L1i.

Also emits `nop_table`: { void (*fn)(uint64_t); uint64_t len; uint64_t count; }

Usage: gen_nops.py --lens 1:15 --counts 256,2048,16384 > kernels.S
"""
import argparse

# Intel-recommended multi-byte NOPs; >9 bytes pads with prefixes.
BASE = {
    1: "90",
    2: "66 90",
    3: "0f 1f 00",
    4: "0f 1f 40 00",
    5: "0f 1f 44 00 00",
    6: "66 0f 1f 44 00 00",
    7: "0f 1f 80 00 00 00 00",
    8: "0f 1f 84 00 00 00 00 00",
    9: "66 0f 1f 84 00 00 00 00 00",
    10: "66 2e 0f 1f 84 00 00 00 00 00",
}


def nop_bytes(n):
    if n <= 10:
        return BASE[n].split()
    return ["66"] * (n - 10) + BASE[10].split()   # extra 0x66 prefixes, up to 15 B


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lens", default="1:15")
    ap.add_argument("--counts", default="256,2048,16384")
    args = ap.parse_args()
    lo, hi = (int(x) for x in args.lens.split(":"))
    counts = [int(x) for x in args.counts.split(",")]

    asm = ["# Generated by gen_nops.py -- do not edit.", "    .text", ""]
    entries = []
    for k in counts:
        for n in range(lo, hi + 1):
            b = nop_bytes(n)
            assert len(b) == n
            sym = f"nop_{n}_{k}"
            asm += [f"    .globl {sym}", "    .p2align 6", f"{sym}:", "1:",
                    f"    .rept {k}", "    .byte " + ", ".join("0x" + x for x in b), "    .endr",
                    "    dec %rdi", "    jnz 1b", "    ret", ""]
            entries.append((sym, n, k))

    asm += ["    .section .data.rel.ro,\"aw\"", "    .p2align 3", "    .globl nop_table", "nop_table:"]
    asm += [f"    .quad {s}, {n}, {k}" for s, n, k in entries]
    asm += ["    .globl nop_table_len", "nop_table_len:", f"    .quad {len(entries)}", ""]
    asm += ["    .section .note.GNU-stack,\"\",@progbits"]
    print("\n".join(asm))


if __name__ == "__main__":
    main()
