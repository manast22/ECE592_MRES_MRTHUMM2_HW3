#!/usr/bin/env python3
"""PMU validation tables: timing results next to the counters, per machine.

Reads results/<machine>/native.csv (timing) and results/<machine>/pmu/native.csv
(common/pmu_verify.sh) for Q1, Q3 and Q15. Timing results and conclusions never
depend on this; it only reports how well the counters agree with them.
-> report/pmu_tables.md
usage: common/pmu_tables.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np
from plotlib import aggregate, load_results

REPO = os.path.dirname(HERE)
PATTERNS = ["taken", "nottaken", "alt", "period:16", "random"]


def series(question, sub=""):
    """{machine: rows} for the native results of one question."""
    data = load_results(os.path.join(REPO, question, "results"), sub)
    return {label.rsplit("_", 1)[0]: d["rows"] for label, d in data.items() if label.endswith("_native")}


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return lines + [""]


def q1(machine, timing, pmu):
    agg = aggregate(timing, ["variant"], "ipc")
    rows = []
    for r in pmu:
        t, p = agg[(r["variant"],)][0], float(r["pmu_ipc"])
        rows.append([r["variant"], f"{t:.3f}", f"{p:.3f}", f"{100 * (p - t) / t:+.1f}%"])
    return table(["variant", "IPC (timing)", "IPC (PMU)", "difference"], rows)


def q3(machine, timing, pmu):
    agg = aggregate(timing, ["pattern"], "cyc_per_branch")
    by = {r["pattern"]: r for r in pmu}
    rows = [[p, f"{agg[(p,)][0]:.2f}", f"{float(by[p]['pmu_cyc_per_branch']):.2f}", f"{float(by[p]['miss_rate']):.5f}"]
            for p in PATTERNS]
    return table(["pattern", "cycles/branch (timing)", "cycles/branch (PMU)", "miss rate (PMU)"], rows)


def q15(machine, timing, pmu):
    t = {k[0]: v[0] for k, v in aggregate(timing, ["pattern"], "cyc_per_branch").items()}
    t_one, t_alt = min(t["taken"], t["nottaken"]), t["alt"]
    P = (t["bias:0.50"] - t_alt) / 0.5
    P16 = (t["bias:0.50"] - t["period:16"]) / 0.5
    c = {r["pattern"]: float(r["pmu_cyc_per_branch"]) for r in pmu}
    m = {r["pattern"]: float(r["miss_rate"]) for r in pmu}
    fs = sorted(p for p in m if p.startswith("bias:"))
    slope = np.polyfit([m[p] for p in fs], [c[p] for p in fs], 1)[0]
    rnd = c["random"]
    out = table(["penalty estimate", "cycles per mispredict"], [
        ["**timing:** fair coin vs. `alt`", f"**{P:.1f}**"],
        ["timing: fair coin vs. `period:16`", f"{P16:.1f}"],
        ["PMU: `random` vs. `alt`, measured miss rate", f"{(rnd - c['alt']) / m['random']:.1f}"],
        ["PMU: `random` vs. `period:16`, measured miss rate", f"{(rnd - c['period:16']) / m['random']:.1f}"],
        ["PMU: `random` vs. mean of `taken`, `nottaken`, measured miss rate",
         f"{(rnd - (c['taken'] + c['nottaken']) / 2) / m['random']:.1f}"],
        ["PMU: slope of cycles vs. measured miss rate over `bias:F`", f"{slope:.1f}"],
    ])
    rows = []
    for p in fs:
        f = float(p[5:])
        base = t_one + 2 * f * (t_alt - t_one)
        rows.append([f"{f:.2f}", f"{(t[p] - base) / P:.3f}", f"{m[p]:.3f}"])
    return out + table(["F", "miss rate implied by timing", "miss rate (PMU)"], rows)


SECTIONS = [
    ("Q1: IPC", "q01_pipelined", "q01_pipelined", q1),
    ("Q3: cost and miss rate per pattern", "q03_branch", "q15_pipeline_depth", q3),
    ("Q15: mispredict penalty", "q15_pipeline_depth", "q15_pipeline_depth", q15),
]

lines = ["# PMU validation tables", "",
         "Generated by `common/pmu_tables.py`. All conclusions come from timing; these tables only "
         "check them afterwards. Native runs only (counters are not visible inside an enclave). "
         "PMU values use the difference method, so they measure steady state over fewer trials "
         "than the timing medians.", ""]
for title, timing_q, pmu_q, fn in SECTIONS:
    timing, pmu = series(timing_q), series(pmu_q, "pmu")
    for machine in sorted(set(timing) & set(pmu)):
        lines += [f"## {title} ({machine})", ""] + fn(machine, timing[machine], pmu[machine])

out = os.path.join(REPO, "report", "pmu_tables.md")
with open(out, "w") as f:
    f.write("\n".join(lines))
print("wrote", out)
