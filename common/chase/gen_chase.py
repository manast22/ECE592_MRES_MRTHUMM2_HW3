#!/usr/bin/env python3
"""Generate pointer-chase kernels (x86-64 GAS) for Q2 / Q4 / Q5.

Every kernel has the signature
    void k(void **p, void **q, uint64_t iters)
and loops `iters` times over:
    load A (chain p)  ; filler x N ; load B (chain q) ; filler x N
(Henry Wong, "Measuring Reorder Buffer Capacity", 2013). The two chains are
independent, so both misses overlap while load B fits in the window behind
load A. Once filler pushes B out of the window, time per iteration doubles.

Special Q2 kernels:
    single : one load per iteration (chain p only)           -> 1 miss / iter
    serial : two loads per iteration, both on chain p        -> 2 misses / iter
    use    : load A; 4 instrs that consume A's result; load B

The output also contains `chase_table`, an array of
    { void (*fn)(void**, void**, uint64_t); const char *kind; uint64_t n; }

Usage: gen_chase.py --kinds nop,int,ymm --n 0:800:8 [--extra] > kernels.S
"""
import argparse

# Registers the filler may write. rax/rcx hold the chains, rdx is the loop
# counter, rdi/rsi hold the output pointers.
INT_REGS = ["r8", "r9", "r10", "r11", "rbx", "r12", "r13", "r14", "r15", "rbp"]
CALLEE_SAVED = ["rbx", "rbp", "r12", "r13", "r14", "r15"]


def filler(kind, n):
    """Return n filler instructions. All are independent of the chains and
    have a high throughput so they never become the bottleneck."""
    out = []
    for i in range(n):
        if kind == "nop":
            # Occupies a ROB entry but writes no register.
            out.append("nop")
        elif kind == "int":
            # Writes one integer register. Not a zeroing idiom, not a mov, so
            # rename cannot eliminate it. 10 short self-chains, ~5 adds/cycle.
            r = INT_REGS[i % len(INT_REGS)]
            out.append(f"add %{r}, %{r}")
        elif kind == "ymm":
            # Writes one vector register; source ymm0 is never written so every
            # instruction is independent.
            out.append(f"vpaddd %ymm0, %ymm0, %ymm{1 + i % 15}")
        elif kind == "mix":
            # Alternate int / vector writers: if the register files are separate,
            # each class fills at half the rate and the knee moves out.
            if i % 2 == 0:
                r = INT_REGS[(i // 2) % len(INT_REGS)]
                out.append(f"add %{r}, %{r}")
            else:
                out.append(f"vpaddd %ymm0, %ymm0, %ymm{1 + (i // 2) % 15}")
        else:
            raise ValueError(kind)
    return out


def kernel(name, body):
    lines = [f"    .globl {name}", "    .p2align 6", f"{name}:"]
    lines += [f"    push %{r}" for r in CALLEE_SAVED]
    lines += ["    mov (%rdi), %rax", "    mov (%rsi), %rcx", "    vpxor %ymm0, %ymm0, %ymm0"]
    lines += ["    .p2align 5", "1:"]
    lines += ["    " + b for b in body]
    lines += ["    dec %rdx", "    jnz 1b"]
    lines += ["    mov %rax, (%rdi)", "    mov %rcx, (%rsi)", "    vzeroupper"]
    lines += [f"    pop %{r}" for r in reversed(CALLEE_SAVED)]
    lines += ["    ret", ""]
    return lines


def parse_range(s):
    lo, hi, step = (int(x) for x in s.split(":"))
    return list(range(lo, hi + 1, step))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kinds", default="nop", help="comma list of nop,int,ymm,mix")
    ap.add_argument("--n", default="0:800:8", help="lo:hi:step filler counts")
    ap.add_argument("--extra", action="store_true", help="add Q2 single/serial/use kernels")
    args = ap.parse_args()

    entries = []   # (symbol, kind, n)
    asm = ["# Generated by gen_chase.py -- do not edit.", "    .text", ""]

    if args.extra:
        asm += kernel("chase_single", ["mov (%rax), %rax"])
        asm += kernel("chase_serial", ["mov (%rax), %rax", "mov (%rax), %rax"])
        asm += kernel("chase_use", ["mov (%rax), %rax",
                                    "lea 1(%rax), %r8", "add %r8, %r9",
                                    "add %r9, %r10", "add %r10, %r11",
                                    "mov (%rcx), %rcx"])
        entries += [("chase_single", "single", 0), ("chase_serial", "serial", 0),
                    ("chase_use", "use", 4)]

    for kind in args.kinds.split(","):
        for n in parse_range(args.n):
            sym = f"chase_{kind}_{n}"
            body = ["mov (%rax), %rax"] + filler(kind, n) + ["mov (%rcx), %rcx"] + filler(kind, n)
            asm += kernel(sym, body)
            entries.append((sym, kind, n))

    asm += ["    .section .rodata"]
    kinds = sorted({k for _, k, _ in entries})
    for k in kinds:
        asm += [f".Lkind_{k}: .asciz \"{k}\""]
    asm += ["", "    .section .data.rel.ro,\"aw\"", "    .p2align 3", "    .globl chase_table", "chase_table:"]
    for sym, k, n in entries:
        asm += [f"    .quad {sym}, .Lkind_{k}, {n}"]
    asm += ["    .globl chase_table_len", "chase_table_len:", f"    .quad {len(entries)}", ""]
    asm += ["    .section .note.GNU-stack,\"\",@progbits"]
    print("\n".join(asm))


if __name__ == "__main__":
    main()
